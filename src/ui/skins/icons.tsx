import type { IconMap, IconGlyphProps } from '../kit/skin';

const glyphs = {
  back: ArrowLeft,
  more: MoreHorizontal,
  search: Search,
  check: Check,
  skip: SkipForward,
  next: ChevronRight,
  send: Send,
  stop: Square,
  mic: Mic,
  book: Book,
  bookOpen: BookOpen,
  teach: GraduationCap,
  derive: Sigma,
  spark: Sparkles,
  clock: Clock,
  chev: ChevronRight,
  branch: GitBranch,
  pin: Pin,
  flag: Flag,
  cards: Layers,
  note: StickyNote,
  person: User,
  shelf: Library,
  add: Plus,
  close: X,
  sync: RefreshCw,
  sun: Sun,
  moon: Moon,
  settings: Settings,
  download: Download,
  upload: Upload,
  trash: Trash2,
  info: Info,
  warning: TriangleAlert,
  help: CircleHelp,
  arrowDown: ArrowDown,
  external: ExternalLink,
};
export function createIconMap(kind: 'paper' | 'glass'): IconMap {
  return Object.fromEntries(
    Object.entries(glyphs).map(([name, Glyph]) => {
      const Impl = name === 'back' && kind === 'glass' ? ChevronLeft : Glyph;
      const Icon = (props: IconGlyphProps) => (
        <Impl {...props} strokeWidth={kind === 'paper' ? 1.7 : 2} />
      );
      return [name, Icon];
    }),
  ) as IconMap;
}
