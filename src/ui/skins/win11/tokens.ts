// RN's multi-layer outset shadows require Android 9; inset requires Android 10.
function fluentShadow(
  outset: string,
  fallback: ShadowStyle,
  inset?: string,
): ShadowStyle {
  if (Platform.OS === 'android' && Number(Platform.Version) < 28)
    return fallback;
  return {
    boxShadow:
      inset && (Platform.OS !== 'android' || Number(Platform.Version) >= 29)
        ? `${inset},${outset}`
        : outset,
  };
}

