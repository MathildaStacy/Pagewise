import { createElement, type ComponentType } from 'react';
import type { KitProps } from './contracts';
import { useSkin } from './context';

export function makeProxy<K extends keyof KitProps>(name: K) {
  const Proxy = (props: KitProps[K]) => {
    const Impl = useSkin().components[name] as ComponentType<KitProps[K]>;
    return createElement(Impl, props);
  };
  Proxy.displayName = `Kit.${name}`;
  return Proxy;
}

